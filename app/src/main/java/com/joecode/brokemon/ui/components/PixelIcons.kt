/** Draws a [PixelIcon] crisp (never blurred), tinted with [tint] and [accent]. */
@Composable
fun PixelIconImage(
    icon: PixelIcon,
    modifier: Modifier = Modifier,
    tint: Color = Color.White,
    accent: Color = tint,
    size: Dp = 24.dp,
    contentDescription: String? = null,
) {
    Canvas(
        modifier
            .size(size)
            .then(if (contentDescription != null) Modifier.semantics { this.contentDescription = contentDescription } else Modifier),
    ) {
        val cell = this.size.minDimension / 16f
        icon.grid.forEachIndexed { y, row ->
            row.forEachIndexed { x, ch ->
                val color = when (ch) {
                    '#' -> tint
                    'o' -> accent
                    else -> null
                }
                // +0.5px overlap hides hairline gaps between cells.
                if (color != null) drawRect(color, Offset(x * cell, y * cell), Size(cell + 0.5f, cell + 0.5f))
            }
        }
    }
}
